app.addEventListener("click", (event) => {
  const sectionButton = event.target.closest("[data-section]");
  if (sectionButton) {
    const section = findSection(sectionButton.dataset.section);
    if (section)
      applyRoute({
        screen: "section",
        sectionId: section.id,
        situationId: null,
      });
    return;
  }
  const situationButton = event.target.closest("[data-situation]");
  if (situationButton) {
    const parent = findSituationParent(situationButton.dataset.situation);
    const situation = parent?.situations.find(
      (item) => item.id === situationButton.dataset.situation,
    );
    if (parent && situation)
      applyRoute({
        screen: "situation",
        sectionId: parent.id,
        situationId: situation.id,
      });
    return;
  }
  const actionButton = event.target.closest("[data-action]");
  if (!actionButton) return;
  if (actionButton.dataset.action === "home") goHome();
  if (actionButton.dataset.action === "sections") {
    goHome();
    scrollToAnchor("sections");
  }
  if (actionButton.dataset.action === "general") goGeneral();
  if (actionButton.dataset.action === "find") {
    goHome();
    scrollToAnchor("sections");
  }
  if (actionButton.dataset.action === "section" && findSection())
    applyRoute({
      screen: "section",
      sectionId: state.sectionId,
      situationId: null,
    });
});

function handleAnchor(event) {
  const link = event.target.closest("a[href^='#']");
  if (!link) return;
  const id = link.getAttribute("href").slice(1);
  event.preventDefault();
  document.querySelector("#site-navigation")?.classList.remove("is-open");
  document
    .querySelector("#mobile-menu-toggle")
    ?.setAttribute("aria-expanded", "false");
  if (!id) {
    goHome();
    return;
  }
  if (id === "general") {
    goGeneral();
    return;
  }
  if (id === "app") {
    scrollToAnchor("app", { focus: true });
    return;
  }
  if (id.startsWith("memo-") && document.getElementById(id)) {
    if (id === "memo-consult") document.getElementById(id).open = true;
    scrollToAnchor(id);
    return;
  }
  if (state.screen !== "home") goHome();
  scrollToAnchor(id);
}
