function findSituationParent(id) {
  return sections.find((section) =>
    section.situations.some((situation) => situation.id === id),
  );
}
function findSituationById(id) {
  const parent = findSituationParent(id);
  return {
    parent,
    situation: parent?.situations.find((situation) => situation.id === id),
  };
}
